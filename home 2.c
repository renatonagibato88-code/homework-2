#include <stdio.h>

int main() {
    // Задаем определенное значение для трат на сладости (X)
    double X = 500.0;

    // Вычисления согласно алгоритму
    double W = X * 4.0;         // Общая сумма в неделю
    double R = W - X;           // Остаток после покупки сладостей
    double S = R / 3.0;         // Сбережения за одну неделю
    double Total = S * 52.0;    // Накопленная сумма за год (52 недели)

    // Вывод результатов на экран
    printf("Траты на сладости в неделю: %.2f руб.\n", X);
    printf("Сумма, накопленная Юрой за год: %.2f руб.\n", Total);

    return 0;
}
